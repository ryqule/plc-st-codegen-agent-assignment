"""Formally check a P02 ST function block through its STruC++ translation.

CBMC checks two arbitrary consecutive 32-bit input transitions. The runner
preserves STruC++'s generated constructor and cycle body, replacing only its
standard-library-heavy generated header with a minimal field/type declaration
so CBMC's C++ frontend can analyze it.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path, PureWindowsPath

from run_st_tests import normalize_strucpp_source


POU_RE = re.compile(r"^\s*(PROGRAM|FUNCTION_BLOCK|FUNCTION)\s+([A-Za-z_][A-Za-z0-9_]*)",
                    re.IGNORECASE | re.MULTILINE)
TYPE_MAP = {
    "BOOL": "bool", "SINT": "signed char", "USINT": "unsigned char",
    "BYTE": "unsigned char", "INT": "int", "UINT": "unsigned int",
    "DINT": "int", "UDINT": "unsigned int", "WORD": "unsigned short",
    "DWORD": "unsigned int", "LWORD": "unsigned long long",
    "LINT": "long long", "ULINT": "unsigned long long",
    "REAL": "float", "LREAL": "double", "CHAR": "char",
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def windows_to_wsl(path: Path) -> str:
    win = PureWindowsPath(str(path.resolve()))
    drive = win.drive.rstrip(":").lower()
    parts = [part for part in win.parts[1:] if part not in ("\\", "/")]
    return "/mnt/" + drive + "/" + "/".join(parts)


def run(source: Path, strucpp: Path, output_dir: Path, harness_template: Path,
        timeout: int) -> dict:
    source = source.resolve()
    strucpp = strucpp.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    source_text = source.read_text(encoding="utf-8-sig")
    match = POU_RE.search(source_text)
    if not match:
        raise ValueError("P02 source has no PROGRAM/FUNCTION_BLOCK/FUNCTION declaration")
    source_pou_name = match.group(2)
    execution_source, normalizations = normalize_strucpp_source(source_text)
    normalized_source = output_dir / "P02_st_input.st"
    normalized_source.write_text(execution_source, encoding="utf-8")

    generated_cpp = output_dir / "P02_translated.cpp"
    generated_hpp = output_dir / "P02_translated.hpp"
    generated_cpp.unlink(missing_ok=True)
    generated_hpp.unlink(missing_ok=True)
    trans = subprocess.run([strucpp, normalized_source.name, "-o", generated_cpp.name],
                           cwd=output_dir, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=timeout,
                           check=False)
    if trans.returncode != 0 or not generated_cpp.is_file() or not generated_hpp.is_file():
        raise RuntimeError("STruC++ translation failed:\n" + (trans.stdout or "") + (trans.stderr or ""))

    header_text = generated_hpp.read_text(encoding="utf-8-sig")
    class_match = re.search(r"class\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{.*?\n\};",
                            header_text, re.DOTALL)
    if not class_match:
        raise ValueError(f"Generated C++ header does not declare a class for {source_pou_name}")
    pou_name = class_match.group(1)
    class_decl = re.sub(r"^\s*virtual\s+~[^\n]+\n", "", class_match.group(0), flags=re.MULTILINE)
    used_types = sorted(set(re.findall(r"\bIEC_([A-Z]+)\b", class_decl)))
    aliases = []
    for name in used_types:
        if name not in TYPE_MAP:
            raise ValueError(f"P02 CBMC adapter does not support IEC_{name}")
        aliases.append(f"typedef {TYPE_MAP[name]} IEC_{name};")
    minimal_header = "\n".join(aliases) + "\n"
    if "SHL(" in generated_cpp.read_text(encoding="utf-8-sig"):
        minimal_header += (
            "inline IEC_DWORD SHL(IEC_DWORD value, IEC_INT shift) "
            "{ return value << shift; }\n"
        )
    function_decls = re.findall(r"^\s*(IEC_[A-Z]+\s+[A-Z_][A-Z0-9_]*\s*\([^;]*\);)",
                                header_text[class_match.end():], re.MULTILINE)
    minimal_header += f"namespace strucpp {{\n{class_decl}\n"
    if function_decls:
        minimal_header += "\n".join(function_decls) + "\n"
    minimal_header += "}\n"
    minimal_header = "#ifndef P02_CBMC_STUB_HPP\n#define P02_CBMC_STUB_HPP\n" + minimal_header + "#endif\n"

    cpp_text = generated_cpp.read_text(encoding="utf-8-sig")
    generated_marker = "// Generated by STruC++ - IEC 61131-3 Structured Text to C++ Compiler"
    first_marker = cpp_text.find(generated_marker)
    second_marker = cpp_text.find(generated_marker, first_marker + len(generated_marker))
    if second_marker >= 0:
        # STruC++ 0.7 emits an empty scaffold before the implementation block.
        cpp_text = cpp_text[second_marker:]
    cpp_text, replaced = re.subn(r'#include\s+"P02_translated\.hpp"',
                                 '#include "P02_cbmc_stub.hpp"', cpp_text)
    if replaced < 1:
        raise ValueError("Could not isolate the generated class header include")
    generated_cpp.write_text(cpp_text, encoding="utf-8")
    stub_path = output_dir / "P02_cbmc_stub.hpp"
    stub_path.write_text(minimal_header, encoding="utf-8")

    harness = harness_template.read_text(encoding="utf-8-sig").replace("__POU_NAME__", pou_name)
    harness_path = output_dir / "harness.cpp"
    harness_path.write_text('#include "P02_cbmc_stub.hpp"\n' + harness, encoding="utf-8")

    cbmc_command = [
        "wsl", "-e", "cbmc", windows_to_wsl(harness_path),
        windows_to_wsl(generated_cpp), "-I", windows_to_wsl(output_dir),
        "--cpp11", "--function", "main", "--unwind", "40",
        "--unwinding-assertions", "--bounds-check", "--pointer-check",
        "--signed-overflow-check", "--undefined-shift-check",
    ]
    try:
        checked = subprocess.run(cbmc_command, capture_output=True, text=True,
                                 encoding="utf-8", errors="replace",
                                 timeout=timeout, check=False)
    except FileNotFoundError as exc:
        raise RuntimeError("WSL/CBMC is unavailable; install CBMC in WSL and retry") from exc
    output = (checked.stdout or "") + (checked.stderr or "")
    (output_dir / "cbmc.log").write_text(output, encoding="utf-8", errors="replace")
    cleaned_output = output.replace("\x00", "")
    verification = re.search(r"\*\*\s+(\d+) of (\d+) failed[^\n]*\nVERIFICATION (SUCCESSFUL|FAILED)",
                              cleaned_output)
    failed_properties = int(verification.group(1)) if verification else None
    checked_properties = int(verification.group(2)) if verification else None
    status = "PASS" if checked.returncode == 0 and verification and verification.group(3) == "SUCCESSFUL" else "FAIL"
    result = {
        "status": status,
        "task_id": "P02",
        "scope": "two arbitrary consecutive 32-bit transitions of the generated POU",
        "source": str(source),
        "source_sha256": sha256(source_text.encode("utf-8")),
        "execution_source_sha256": sha256(execution_source.encode("utf-8")),
        "source_normalizations": normalizations,
        "pou_name": pou_name,
        "strucpp": str(strucpp),
        "strucpp_version": subprocess.run([str(strucpp), "--version"], capture_output=True,
                                            text=True, encoding="utf-8", errors="replace",
                                            timeout=10, check=False).stdout.strip(),
        "cbmc": "5.95.1 (Ubuntu 24.04 WSL)",
        "generated_cpp_sha256": sha256(generated_cpp.read_bytes()),
        "generated_header_sha256": sha256(generated_hpp.read_bytes()),
        "checked_cpp_sha256": sha256(cpp_text.encode("utf-8")),
        "checked_stub_sha256": sha256(minimal_header.encode("utf-8")),
        "checked_harness_sha256": sha256(harness_path.read_bytes()),
        "header_adapter": "generated class fields retained; standard-library header replaced by IEC type aliases and SHL",
        "cbmc_args": cbmc_command[5:],
        "exit_code": checked.returncode,
        "verified_properties": checked_properties,
        "failed_properties": failed_properties,
        "cbmc_log": "cbmc.log",
        "cbmc_log_sha256": sha256((output_dir / "cbmc.log").read_bytes()),
        "output": verification.group(0) if verification else cleaned_output[-6000:].strip(),
        "cprover_nondet_note": "CBMC's no-body warning for __CPROVER_nondet_uint is expected; the function is a symbolic input primitive.",
    }
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--strucpp", type=Path, required=True)
    parser.add_argument("--harness-template", type=Path,
                        default=Path(__file__).resolve().parents[1] / "tests" / "structured_text" / "P02_cbmc_harness.cpp")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--timeout", type=int, default=180)
    args = parser.parse_args()
    result = run(args.source, args.strucpp, args.output_dir, args.harness_template, args.timeout)
    encoded = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    result_path = args.output_dir / "result.json"
    result_path.write_text(encoded, encoding="utf-8")
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print(encoded, end="")
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
